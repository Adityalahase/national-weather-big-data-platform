"""
Weather Data Loading — PostgreSQL
SIH 2026 - National Weather Big Data Analytics Platform (PS 26069)
Role: Data Engineer

Reads the latest cleaned CSV produced by `cleaning/clean_weather.py` and
inserts its records into the existing `weather_data` table in the
`weather_platform` PostgreSQL database.

Does NOT create or modify the database/table — it must already exist.

Credentials are read from environment variables (see .env.example) and
are never hardcoded.
"""

import os
import sys
from pathlib import Path

import pandas as pd
import psycopg2

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
PROCESSED_DATA_DIR = Path(__file__).resolve().parent.parent / "cleaning" / "data" / "processed"

TABLE_NAME = "weather_data"

# Columns in the cleaned CSV that map 1:1 to weather_data table columns
# (id is auto-generated by the DB, so it is intentionally excluded)
INSERT_COLUMNS = [
    "timestamp",
    "latitude",
    "longitude",
    "timezone",
    "temperature_c",
    "relative_humidity_pct",
    "precipitation_mm",
    "wind_speed_kmh",
    "weather_code",
]

INSERT_SQL = f"""
    INSERT INTO {TABLE_NAME} (
        timestamp, latitude, longitude, timezone,
        temperature_c, relative_humidity_pct, precipitation_mm,
        wind_speed_kmh, weather_code
    )
    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
"""


def load_env_file():
    """Load a local .env file (if present) without adding a new dependency."""
    env_path = Path(__file__).resolve().parent / ".env"
    if not env_path.exists():
        return
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip())


def get_db_config() -> dict:
    """Read DB connection settings from environment variables. Never hardcode."""
    required = ["DB_HOST", "DB_PORT", "DB_NAME", "DB_USER", "DB_PASSWORD"]
    missing = [var for var in required if not os.environ.get(var)]
    if missing:
        print(f"[ERROR] Missing required environment variable(s): {', '.join(missing)}")
        print("Set them in your shell, or copy .env.example to .env and fill it in.")
        sys.exit(1)

    return {
        "host": os.environ["DB_HOST"],
        "port": os.environ["DB_PORT"],
        "dbname": os.environ["DB_NAME"],
        "user": os.environ["DB_USER"],
        "password": os.environ["DB_PASSWORD"],
    }


def find_latest_csv() -> Path:
    """Return the most recently modified cleaned CSV from cleaning/data/processed/."""
    if not PROCESSED_DATA_DIR.exists():
        print(f"[ERROR] Processed data directory not found: {PROCESSED_DATA_DIR}")
        sys.exit(1)

    csv_files = sorted(PROCESSED_DATA_DIR.glob("weather_cleaned_*.csv"))
    if not csv_files:
        print(f"[ERROR] No cleaned CSV files found in: {PROCESSED_DATA_DIR}")
        print("Run cleaning/clean_weather.py first.")
        sys.exit(1)

    latest = max(csv_files, key=lambda p: p.stat().st_mtime)
    return latest


def load_csv(filepath: Path) -> pd.DataFrame:
    """Read the cleaned CSV into a DataFrame."""
    try:
        df = pd.read_csv(filepath, parse_dates=["timestamp"])
    except (OSError, pd.errors.ParserError) as exc:
        print(f"[ERROR] Failed to read CSV {filepath}: {exc}")
        sys.exit(1)

    missing_cols = [c for c in INSERT_COLUMNS if c not in df.columns]
    if missing_cols:
        print(f"[ERROR] CSV is missing expected column(s): {', '.join(missing_cols)}")
        sys.exit(1)

    return df


def insert_records(conn, df: pd.DataFrame) -> int:
    """Insert all rows from the DataFrame into weather_data using a parameterized query."""
    inserted = 0
    with conn.cursor() as cur:
        for _, row in df.iterrows():
            # Convert pandas NaN -> None so psycopg2 stores SQL NULL, not the
            # string "nan". No values are invented here.
            values = [row[col] if pd.notna(row[col]) else None for col in INSERT_COLUMNS]
            cur.execute(INSERT_SQL, values)
            inserted += 1
    conn.commit()
    return inserted


def main():
    load_env_file()
    db_config = get_db_config()

    latest_csv = find_latest_csv()
    print(f"Reading latest cleaned CSV: {latest_csv}")

    df = load_csv(latest_csv)
    record_count = len(df)

    conn = None
    try:
        conn = psycopg2.connect(**db_config)
    except psycopg2.OperationalError as exc:
        print(f"[ERROR] Could not connect to PostgreSQL: {exc}")
        sys.exit(1)

    try:
        inserted = insert_records(conn, df)
        status = "SUCCESS"
    except psycopg2.Error as exc:
        conn.rollback()
        inserted = 0
        status = "FAILED"
        print(f"[ERROR] Insertion failed, transaction rolled back: {exc}")
    finally:
        conn.close()

    print("\nSummary:")
    print(f"  Input CSV:          {latest_csv}")
    print(f"  Records in CSV:     {record_count}")
    print(f"  Database:           {db_config['dbname']}")
    print(f"  Records inserted:   {inserted}")
    print(f"  Insertion status:   {status}")

    if status == "FAILED":
        sys.exit(1)

    print("\n[SUCCESS] Records loaded into PostgreSQL and connection closed safely.")


if __name__ == "__main__":
    main()
